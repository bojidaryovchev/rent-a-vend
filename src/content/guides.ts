/**
 * The authority layer.
 *
 * Keyword research found the rental market is ~300 searches/month while permit,
 * registration and tax questions carry ~710/month at difficulty 0
 * (`docs/seo-keyword-research.md` §3). These pages exist to answer those, and
 * they earn their place twice over: a workplace manager putting a machine in
 * their own building genuinely needs to know the permit and БАБХ position
 * before they sign, and D18 already commits us to explaining it openly.
 *
 * Written answer-first. AI Overviews appear on four of the six queries sampled,
 * and the first paragraph is what gets cited - so each guide opens with a
 * direct answer that stands alone, then explains.
 *
 * ACCURACY RULE. Every legal reference below was verified against a named
 * source before publication, and the specific ones (Чл. 61з ЗМДТ, Наредба
 * № Н-18, Приложение № 4) are cited so a reader can check them. Where the
 * answer genuinely depends on the case, these pages say so and point at ОДБХ or
 * the municipality rather than guessing. Publishing a confident wrong answer
 * about someone's legal obligations would cost more than the traffic is worth,
 * and would contradict the one thing this site is positioned on.
 */

